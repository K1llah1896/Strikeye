// Package playback builds the hand-off needed to open a demo in CS2.
package playback

import (
	"fmt"
	"net/url"
	"path/filepath"
	"strings"
)

// AppID is Counter-Strike 2 on Steam.
const AppID = 730

// URL returns a steam:// URL that launches CS2 with +playdemo for demoPath.
func URL(demoPath string) string {
	return fmt.Sprintf("steam://rungameid/%d//+playdemo%%20%s", AppID, escapeArg(demoPath))
}

// Config returns a cfg body that seeks playback to startTick. An empty string
// means no seek config is needed.
func Config(startTick int64) string {
	if startTick <= 0 {
		return ""
	}
	return fmt.Sprintf("// generated by Strikeye\ndemo_goto %d\n", startTick)
}

// DemoFileName returns the file name CS2 should load, with forward slashes so
// the same value works in the cfg and the launch URL.
func DemoFileName(demoPath string) string {
	return filepath.ToSlash(filepath.Base(demoPath))
}

func escapeArg(s string) string {
	escaped := url.PathEscape(s)
	// PathEscape leaves '+' alone, but Steam splits rungameid args on '+'.
	return strings.ReplaceAll(escaped, "+", "%2B")
}
