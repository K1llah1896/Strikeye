package recorder

import (
	"fmt"
	"io"
	"math"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

const (
	// PreSeekWarmupTicks is the number of ticks before start_tick used to seek
	// and stabilize the spectator camera before mirv_streams record start fires.
	PreSeekWarmupTicks int64 = 128
)

// RenderSegment represents a single tick window to capture for a render task.
type RenderSegment struct {
	TaskID         int64 `json:"task_id"`
	SegIndex       int   `json:"seg_index"`
	StartTick      int64 `json:"start_tick"`
	EndTick        int64 `json:"end_tick"`
	TargetSpecSlot int   `json:"target_spec_slot"`
}

// BootCFGOptions configures _strikeye_boot_<id>.cfg generation.
type BootCFGOptions struct {
	SessionID     string
	TempRenderDir string
	DemoPlayArg   string
	DemoEndTick   int64
	TickRate      float64
	Segments      []RenderSegment
}

// LaunchOptions configures HLAE.exe -customLoader invocation.
type LaunchOptions struct {
	SessionID         string
	HLAEExe           string
	AfxHookSource2DLL string
	CS2Exe            string
	BootCFGName       string
	LogFileName       string
	Width             int
	Height            int
}

// ClampSegmentEndTick applies demo_end_guard so CS2 never hits physical demo EOF
// during a capture segment: end_tick <= demo_end_tick - ceil(1.5 * tick_rate).
func ClampSegmentEndTick(endTick, demoEndTick int64, tickRate float64) int64 {
	if demoEndTick <= 0 {
		return endTick
	}
	if tickRate <= 0 {
		tickRate = 64
	}
	guard := int64(math.Ceil(1.5 * tickRate))
	maxSafe := demoEndTick - guard
	if maxSafe < 1 {
		maxSafe = 1
	}
	if endTick > maxSafe {
		return maxSafe
	}
	return endTick
}

// PreparePlaybackDemo copies srcDemoPath to a temporary _strikeye_playback_<sessionID>.dem
// inside targetDir so CS2 plays an isolated copy without locking or altering the original.
func PreparePlaybackDemo(srcDemoPath, targetDir, sessionID string) (string, error) {
	if srcDemoPath == "" || targetDir == "" || sessionID == "" {
		return "", fmt.Errorf("srcDemoPath, targetDir, and sessionID are required")
	}
	if err := os.MkdirAll(targetDir, 0o755); err != nil {
		return "", fmt.Errorf("create playback dir: %w", err)
	}
	dstName := fmt.Sprintf("_strikeye_playback_%s.dem", sanitizeToken(sessionID))
	dstPath := filepath.Join(targetDir, dstName)

	in, err := os.Open(srcDemoPath)
	if err != nil {
		return "", fmt.Errorf("open source demo %q: %w", srcDemoPath, err)
	}
	defer in.Close()

	out, err := os.OpenFile(dstPath, os.O_CREATE|os.O_WRONLY|os.O_TRUNC, 0o644)
	if err != nil {
		return "", fmt.Errorf("create playback demo %q: %w", dstPath, err)
	}
	if _, err := io.Copy(out, in); err != nil {
		_ = out.Close()
		_ = os.Remove(dstPath)
		return "", fmt.Errorf("copy playback demo: %w", err)
	}
	if err := out.Close(); err != nil {
		_ = os.Remove(dstPath)
		return "", fmt.Errorf("close playback demo: %w", err)
	}
	return dstPath, nil
}

// BuildBootCFG generates the _strikeye_boot_<id>.cfg script content using HLAE
// mirv_streams and mirv_cmd addAtTick without modifying any VPK files.
func BuildBootCFG(opts BootCFGOptions) (string, error) {
	if opts.SessionID == "" {
		return "", fmt.Errorf("session_id is required")
	}
	if opts.TempRenderDir == "" {
		return "", fmt.Errorf("temp_render_dir is required")
	}
	if opts.DemoPlayArg == "" {
		return "", fmt.Errorf("demo_play_arg is required")
	}
	if len(opts.Segments) == 0 {
		return "", fmt.Errorf("at least one segment is required")
	}

	segs := make([]RenderSegment, len(opts.Segments))
	copy(segs, opts.Segments)
	sort.Slice(segs, func(i, j int) bool {
		if segs[i].StartTick != segs[j].StartTick {
			return segs[i].StartTick < segs[j].StartTick
		}
		if segs[i].TaskID != segs[j].TaskID {
			return segs[i].TaskID < segs[j].TaskID
		}
		return segs[i].SegIndex < segs[j].SegIndex
	})

	var b strings.Builder
	b.WriteString("// Auto-generated by Strikeye Phase 4 recorder (zero-VPK mode)\n")
	b.WriteString("sv_cheats 1\n")
	b.WriteString("cl_draw_only_deathnotices 1\n")
	b.WriteString("cl_drawhud_force_radar 1\n")
	b.WriteString("spec_show_xray 0\n")
	b.WriteString("mirv_streams record screen enabled 1\n")
	b.WriteString("mirv_streams record startMovieWav 1\n")
	fmt.Fprintf(&b, "mirv_streams record name %q\n", filepath.ToSlash(opts.TempRenderDir))
	b.WriteString("mirv_cmd clear\n")

	var maxEndTick int64
	for _, seg := range segs {
		startTick := seg.StartTick
		if startTick < 0 {
			startTick = 0
		}
		endTick := ClampSegmentEndTick(seg.EndTick, opts.DemoEndTick, opts.TickRate)
		if endTick <= startTick {
			endTick = startTick + 1
		}
		if endTick > maxEndTick {
			maxEndTick = endTick
		}

		seekTick := startTick - PreSeekWarmupTicks
		if seekTick < 0 {
			seekTick = 0
		}

		fmt.Fprintf(&b, "mirv_cmd addAtTick %d \"spec_mode 5; spec_player %d; demo_timescale 1\"\n",
			seekTick, seg.TargetSpecSlot)
		fmt.Fprintf(&b, "mirv_cmd addAtTick %d \"mirv_streams record start; echo STRIKEYE_EVT:START:%d:%d\"\n",
			startTick, seg.TaskID, seg.SegIndex)
		fmt.Fprintf(&b, "mirv_cmd addAtTick %d \"mirv_streams record end; demo_pause; echo STRIKEYE_EVT:END:%d:%d\"\n",
			endTick, seg.TaskID, seg.SegIndex)
	}

	quitTick := maxEndTick + 16
	if opts.DemoEndTick > 0 {
		clampedQuit := ClampSegmentEndTick(quitTick, opts.DemoEndTick, opts.TickRate)
		if clampedQuit > maxEndTick {
			quitTick = clampedQuit
		} else {
			quitTick = maxEndTick + 1
		}
	}
	fmt.Fprintf(&b, "mirv_cmd addAtTick %d \"quit\"\n", quitTick)
	fmt.Fprintf(&b, "playdemo %q\n", filepath.ToSlash(opts.DemoPlayArg))
	fmt.Fprintf(&b, "echo STRIKEYE_DEMO_LOADED:%s\n", sanitizeToken(opts.SessionID))
	return b.String(), nil
}

// BuildHLAEArgs constructs the HLAE.exe -customLoader argument slice.
// It enforces -insecure and rejects forbidden online flags (-secure, +connect).
func BuildHLAEArgs(opts LaunchOptions) ([]string, error) {
	if opts.SessionID == "" {
		return nil, fmt.Errorf("session_id is required")
	}
	if opts.HLAEExe == "" || opts.AfxHookSource2DLL == "" || opts.CS2Exe == "" {
		return nil, fmt.Errorf("hlae_exe, afx_hook_source2_dll, and cs2_exe are required")
	}
	w := opts.Width
	if w <= 0 {
		w = 1920
	}
	h := opts.Height
	if h <= 0 {
		h = 1080
	}
	logFile := opts.LogFileName
	if logFile == "" {
		logFile = fmt.Sprintf("_strikeye_session_%s.log", sanitizeToken(opts.SessionID))
	}
	bootCFG := opts.BootCFGName
	if bootCFG == "" {
		bootCFG = fmt.Sprintf("_strikeye_boot_%s.cfg", sanitizeToken(opts.SessionID))
	}

	cs2CmdLine := fmt.Sprintf(
		"-insecure -novid -nojoy -console -sw -w %d -h %d -con_logfile %s +exec %s",
		w, h, logFile, bootCFG,
	)
	if strings.Contains(cs2CmdLine, "-secure") || strings.Contains(cs2CmdLine, "+connect") {
		return nil, fmt.Errorf("forbidden online flag in cs2 command line")
	}

	return []string{
		"-customLoader",
		"-noGui",
		"-autoStart",
		"-hookDllPath", opts.AfxHookSource2DLL,
		"-programPath", opts.CS2Exe,
		"-cmdLine", cs2CmdLine,
	}, nil
}
